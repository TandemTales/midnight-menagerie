"""Round 57 JASPER: the rooms under the boards, drawn by code.

Everything here is deterministic numpy: a relief map (mouldings, stones, boards,
rug pile), an albedo, ink where the relief turns, then the room's OWN lights raked
across that relief so a moulding catches the candle on the side that faces it.
Nothing is generated by a model; the only inputs are kit/damask.webp (the samples'
scrollwork) and kit/grain.webp's idea of tooth.

    python tools/prep_r57_jasper.py            # writes game/assets/ui/r57-jasper/

Each room is painted twice, at the two sizes judged and shipped (1600x900 and
1280x800), because the page, its sconces and its candles do not stay at the same
fraction of the screen between them: the light has to fall where the object is.
"""
from pathlib import Path
import numpy as np
from scipy import ndimage as ndi
from scipy.spatial import cKDTree
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'game/assets/ui/r57-jasper'
OUT.mkdir(parents=True, exist_ok=True)
KIT = ROOT / 'game/assets/ui/kit'

CANDLE = np.array([1.00, .70, .40])
EMBER = np.array([1.00, .50, .22])
MOON = np.array([.50, .62, 1.00])


def noise(h, w, s, seed):
    r = np.random.default_rng(seed)
    n = ndi.gaussian_filter(r.standard_normal((h, w)), s, mode='wrap')
    return n / (n.std() + 1e-9)


def aniso(h, w, sy, sx, seed):
    r = np.random.default_rng(seed)
    n = ndi.gaussian_filter(r.standard_normal((h, w)), (sy, sx), mode='wrap')
    return n / (n.std() + 1e-9)


def fbm(h, w, s, seed, oct=4):
    out = np.zeros((h, w)); a = 1.0
    for i in range(oct):
        out += a * noise(h, w, max(.6, s / 2 ** i), seed + i * 17)
        a *= .55
    return out / out.std()


def smooth(a, b, x):
    t = np.clip((x - a) / (b - a + 1e-9), 0, 1)
    return t * t * (3 - 2 * t)


def mix(a, b, t):
    t = np.asarray(t)
    if t.ndim == 2:
        t = t[..., None]
    return a * (1 - t) + b * t


def tile(path, size, w, h):
    """The samples' damask as a repeating mask."""
    im = Image.open(path).convert('RGBA')
    tw = size; th = round(im.height * size / im.width)
    im = im.resize((tw, th), Image.LANCZOS)
    a = np.asarray(im, float) / 255
    p = a[..., 3] * a[..., :3].mean(-1)
    p = p / max(p.max(), 1e-6)
    ys = np.arange(h) % th; xs = np.arange(w) % tw
    return p[np.ix_(ys, xs)], tw, th


class Room:
    def __init__(s, W, H, seed):
        s.W, s.H, s.seed = W, H, seed
        s.yy, s.xx = np.mgrid[0:H, 0:W].astype(float)
        s.A = np.zeros((H, W, 3))      # albedo
        s.R = np.zeros((H, W))         # relief, in px of height
        s.K = np.ones((H, W))          # ink, multiplied at the end
        s.L = np.zeros((H, W, 3))      # the light gathered so far
        s.add = np.zeros((H, W, 3))    # air: light seen in the room, not on a surface

    # ── the wall ──────────────────────────────────────────────────────────────
    def wall(s, top, bottom):
        W, H = s.W, s.H
        m = (s.yy < bottom)[..., None]
        P, tw, th = tile(KIT / 'damask.webp', int(W * .118), W, H)
        strip = int(W * .147)
        # strips of paper hung by hand: each one a little off the next
        P2 = P.copy()
        for i, x0 in enumerate(range(0, W, strip)):
            dy = (i * 37) % th
            P2[:, x0:x0 + strip] = np.roll(P, dy, axis=0)[:, x0:x0 + strip]
        P = ndi.gaussian_filter(P2, .7)
        wear = fbm(H, W, 90, s.seed + 1)
        stain = fbm(H, W, 150, s.seed + 2)
        drip = aniso(H, W, 70, 2.2, s.seed + 3)
        pat = P * smooth(-1.4, .4, wear + .4)
        base = np.array([.165, .095, .215])
        hi = np.array([.56, .39, .66])
        A = mix(base[None, None], hi[None, None], np.clip(pat * .78, 0, 1))
        A *= (1 + .16 * stain[..., None]) * (1 + .05 * drip[..., None])
        # warm foxing and the paper going dark in tide marks
        fox = smooth(1.1, 1.9, fbm(H, W, 34, s.seed + 4))
        A = mix(A, A * np.array([.72, .55, .5]), fox * .85)
        s.A = np.where(m, A, s.A)
        s.R += (P * 2.6 + .35 * fbm(H, W, 3, s.seed + 5)) * m[..., 0]
        # the seams
        for x0 in range(strip, W, strip):
            d = np.abs(s.xx - x0 - 1.6 * noise(H, W, 40, s.seed + x0)[:, 0:1])
            s.K *= 1 - .34 * smooth(1.6, .4, d) * m[..., 0]
        # a picture rail and frieze far above; mostly under the plaque
        rail = (s.yy >= top) & (s.yy < top + 14)
        s.A[rail] = np.array([.24, .15, .10])
        s.R += 5 * np.sin(np.clip((s.yy - top) / 14, 0, 1) * np.pi) * rail

    # ── the wainscot ──────────────────────────────────────────────────────────
    def wood(s, vertical, seed, tone=(.335, .205, .135)):
        H, W = s.H, s.W
        a = aniso(H, W, 60, 1.3, seed) if vertical else aniso(H, W, 1.3, 60, seed)
        b = aniso(H, W, 18, .7, seed + 1) if vertical else aniso(H, W, .7, 18, seed + 1)
        c = fbm(H, W, 60, seed + 2)
        g = .5 + .5 * np.sin((s.xx if vertical else s.yy) * .35 + c * 4 + a * 1.6)
        t = 1 + .17 * a + .10 * b + .14 * c - .16 * g
        return np.array(tone)[None, None] * t[..., None], (a * .22 + b * .14)

    def wainscot(s, y0, y1, period):
        H, W = s.H, s.W
        Av, Gv = s.wood(True, s.seed + 20)
        Ah, Gh = s.wood(False, s.seed + 30, (.30, .185, .12))
        cap = max(18, int((y1 - y0) * .13))
        skirt = max(20, int((y1 - y0) * .17))
        band = (s.yy >= y0) & (s.yy < y1)
        A = Av.copy(); R = np.zeros((H, W)) + 6.0 + Gv
        # panels of hand-cut width
        r = np.random.default_rng(s.seed + 7)
        x = -r.integers(10, period // 2)
        stile = int(period * .17)
        p0 = y0 + cap + int((y1 - y0) * .075)
        p1 = y1 - skirt - int((y1 - y0) * .07)
        mid = np.zeros((H, W), bool)
        idx = 0
        while x < W:
            pw = int(period * r.uniform(.94, 1.06))
            a, b = x + stile, x + pw
            mask = (s.xx >= a) & (s.xx < b) & (s.yy >= p0) & (s.yy < p1)
            if mask.any():
                dx = np.minimum(s.xx - a, b - s.xx); dy = np.minimum(s.yy - p0, p1 - s.yy)
                d = np.minimum(dx, dy)
                # groove, sloping field, raised centre
                prof = np.where(d < 3, 6 - d * 2.4, np.where(d < 20, -1.2 + (d - 3) * .42, 5.9))
                R = np.where(mask, prof + Gv * .7, R)
                tone = r.uniform(.84, 1.12)
                A = np.where(mask[..., None], A * tone * np.array([1, r.uniform(.95, 1.03), r.uniform(.9, 1.05)]), A)
                s.K *= 1 - .62 * (mask & (d < 2.2))
                # the field's light rubbed centre
                rub = smooth(16, 60, d) * (1 + .4 * fbm(H, W, 22, s.seed + 40 + idx)) * .10
                A = np.where(mask[..., None], A * (1 + rub[..., None]), A)
            idx += 1
            x += pw
        # the lower and the top rail run horizontally
        rails = (s.yy >= y0) & (s.yy < p0) | (s.yy >= p1) & (s.yy < y1)
        A = np.where(rails[..., None], Ah, A)
        R = np.where(rails, 6.0 + Gh, R)
        # chair rail: a real run of moulding, with one parcel-gilt bead
        t = (s.yy - y0) / cap
        c = (t >= 0) & (t < 1)
        prof = 13 * np.sin(np.clip(t, 0, 1) * np.pi) ** .6 + 4 * np.sin(np.clip(t, 0, 1) * 3 * np.pi)
        R = np.where(c, 6 + prof, R)
        gilt = (t > .18) & (t < .29)
        wear = fbm(H, W, 7, s.seed + 44)
        A = np.where((gilt & (wear > -.8))[..., None], np.array([.82, .60, .30])[None, None] * (1 + .25 * wear[..., None]), A)
        s.K *= 1 - .62 * ((np.abs(t - .03) < .05) | (np.abs(t - .96) < .05) | (np.abs(t - .42) < .03))
        # skirting
        t2 = (s.yy - (y1 - skirt)) / skirt
        c2 = (t2 >= 0) & (t2 < 1)
        R = np.where(c2, 9 + 5 * np.sin(np.clip(t2, 0, 1) * np.pi * 1.3), R)
        A = np.where(c2[..., None], Ah * .82, A)
        s.K *= 1 - .6 * (np.abs(t2 - .05) < .05)
        s.K *= 1 - .7 * (np.abs(t2 - .98) < .05)
        # knocks and scratches: a hundred years of chair backs
        im = Image.new('L', (W * 2, H * 2), 0); dr = ImageDraw.Draw(im)
        for _ in range(int(W * .13)):
            px, py = r.uniform(0, W * 2), r.uniform(y0 * 2, y1 * 2)
            ang = r.normal(0, .5) + (np.pi / 2 if r.random() < .3 else 0); ln = r.uniform(6, 60)
            dr.line([px, py, px + np.cos(ang) * ln, py + np.sin(ang) * ln], fill=int(r.uniform(90, 220)), width=1)
        sc = np.asarray(im.resize((W, H), Image.LANCZOS), float) / 255
        s.A = np.where(band[..., None], A, s.A)
        s.R = np.where(band, R, s.R)
        s.K *= 1 - sc * .45 * band
        # rubbed edges read brighter where the relief is proud
        proud = np.clip(ndi.gaussian_filter(R, 1.5) - ndi.gaussian_filter(R, 6), 0, 3) / 3
        s.A = np.where(band[..., None], s.A * (1 + .5 * proud[..., None] * smooth(-.4, 1, fbm(H, W, 12, s.seed + 46))[..., None]), s.A)

    # ── floors ────────────────────────────────────────────────────────────────
    def floor_uv(s, fy, depth, vx):
        """World x and depth on the floor plane, for a camera whose horizon stands depth px above fy."""
        hy = fy - depth
        d = np.maximum(s.yy - hy, 1.0)
        return (s.xx - vx) * depth / d, depth * (1 - depth / d) * 3.2, depth / d

    def boards(s, fy, depth, vx, pw, tone=(.30, .19, .125)):
        H, W = s.H, s.W
        X, Z, sc = s.floor_uv(fy, depth, vx)
        m = s.yy >= fy
        r = np.random.default_rng(s.seed + 60)
        idx = np.floor(X / pw).astype(int)
        n = 400
        offs = r.uniform(0, 900, n); tones = r.uniform(.68, 1.22, n); warms = r.uniform(.9, 1.1, n)
        ii = idx % n
        jz = (Z + offs[ii]) / 640
        jn = np.floor(jz).astype(int)
        tt = tones[ii] * (1 + .10 * np.sin(jn * 12.9898 + ii * 78.233))
        # grain in world space: long along the board
        tex = aniso(1024, 1024, 26, 1.1, s.seed + 61)
        tex2 = aniso(1024, 1024, 60, 3.5, s.seed + 62)
        u = ((X * 1.7).astype(int) + (ii * 131)) % 1024; v = ((Z * .9).astype(int) + (ii * 57)) % 1024
        g = tex[v, u]; g2 = tex2[v, u]
        rings = .5 + .5 * np.sin(X * .55 + g2 * 3 + ii * 2.1)
        A = np.array(tone)[None, None] * (tt * (1 + .22 * g + .15 * g2 - .14 * rings))[..., None]
        A[..., 2] *= warms[ii]
        # worn path: boards paler and rubbed in the middle of the room
        wear = smooth(-.3, 1.4, fbm(H, W, 40, s.seed + 63))
        A = A * (1 + .16 * wear[..., None])
        frac = X / pw - np.floor(X / pw)
        gap = np.minimum(frac, 1 - frac) * pw / sc      # px to the board edge
        R = np.minimum(gap, 3.2) * .9 + g * .22
        ink = 1 - .86 * smooth(1.5, .4, gap)
        # butt joints
        fz = (jz - np.floor(jz)); jd = np.minimum(fz, 1 - fz) * 640 * .35
        ink *= 1 - .72 * smooth(1.2, .3, jd)
        R = np.minimum(R, np.minimum(jd, 3.2) * .9 + g * .22)
        s.A = np.where(m[..., None], A, s.A)
        s.R = np.where(m, R, s.R)
        s.K *= np.where(m, ink, 1)
        # nail heads either side of each joint
        for i in range(-30, 30):
            pass
        s.floor = (fy, depth, vx)

    def flags(s, fy, depth, vx, cell, tone=(.34, .30, .35)):
        H, W = s.H, s.W
        X, Z, sc = s.floor_uv(fy, depth, vx)
        m = s.yy >= fy
        r = np.random.default_rng(s.seed + 70)
        # jittered brick of seeds
        pts = []
        for j in range(-2, 42):
            for i in range(-80, 80):
                pts.append(((i + (.5 if j % 2 else 0) + r.uniform(-.34, .34)) * cell,
                            (j + r.uniform(-.34, .34)) * cell * .62))
        pts = np.array(pts)
        tree = cKDTree(pts)
        wx = X + 5 * noise(H, W, 14, s.seed + 71); wz = Z + 4 * noise(H, W, 14, s.seed + 72)
        pos = np.stack([wx[m], wz[m]], -1)
        dist, ids = tree.query(pos, k=2)
        gap = (dist[:, 1] - dist[:, 0])
        G = np.full((H, W), 99.0); G[m] = gap
        I = np.zeros((H, W), int); I[m] = ids[:, 0]
        tones = r.uniform(.62, 1.34, len(pts)); hue = r.uniform(-1, 1, len(pts))
        t = tones[I]
        A = np.array(tone)[None, None] * t[..., None]
        A = mix(A, A * np.array([1.18, .94, .78]), np.clip(hue[I], 0, 1) * .85)
        A = mix(A, A * np.array([.86, .90, 1.2]), np.clip(-hue[I], 0, 1) * .8)
        pit = fbm(H, W, 3.5, s.seed + 73); cloud = fbm(H, W, 18, s.seed + 74)
        A *= (1 + .17 * pit + .15 * cloud)[..., None]
        # moss and old wax in the joints
        px = G * sc  # px to the joint, at this depth
        chip = 1.3 + 1.2 * smooth(.5, 1.6, fbm(H, W, 5, s.seed + 75))
        ink = 1 - .94 * smooth(chip, chip * .4, px)
        R = np.minimum(px, 6) * .8 + pit * .5
        s.A = np.where(m[..., None], A, s.A)
        s.R = np.where(m, R, s.R)
        s.K *= np.where(m, ink, 1)
        s.floor = (fy, depth, vx)

    def rug(s, cx, half, z0, z1):
        """A rug lying on the boards in world coordinates: border, gold rule, diamonds, field, fringe."""
        fy, depth, vx = s.floor
        H, W = s.H, s.W
        X, Z, sc = s.floor_uv(fy, depth, vx)
        cxw = cx - vx
        dx = half - np.abs(X - cxw)
        dz = np.minimum(Z - z0, z1 - Z)
        d = np.minimum(dx, dz * 1.0)
        m = (d > 0) & (s.yy >= fy)
        pile = fbm(H, W, 1.1, s.seed + 80, 2)
        ox = np.array([.30, .075, .085]); deep = np.array([.15, .058, .115])
        gold = np.array([.60, .44, .23]); ind = np.array([.10, .09, .22]); lav = np.array([.36, .26, .46])
        A = np.tile(deep[None, None], (H, W, 1))
        # field: a repeat of small stepped medallions
        fu = (X - cxw) / 86; fv = Z / 62
        rep = np.abs(np.abs(((fu + .5 * (np.floor(fv) % 2)) % 1) - .5) + np.abs((fv % 1) - .5))
        A = mix(A, ox, smooth(.40, .34, rep))
        A = mix(A, gold * .75, smooth(.05, .02, np.abs(rep - .24)))
        A = mix(A, lav * .6, smooth(.13, .10, rep))
        # bands from the edge in
        A = np.where((d < 54)[..., None], np.tile(ox[None, None], (H, W, 1)) * 1.0, A)
        along = np.where(dx < dz, Z, X)
        diam = np.abs(((along / 26) % 1) - .5) * 2
        band = (d > 20) & (d < 44)
        w = np.abs((d - 32) / 12)
        A = np.where((band & (diam + w < 1.0))[..., None], ind[None, None] * 1.5, A)
        A = np.where((band & (diam + w < .55))[..., None], gold[None, None], A)
        A = np.where((((d > 14) & (d < 18.5)) | ((d > 47) & (d < 51)))[..., None], gold[None, None], A)
        A = np.where(((d < 7))[..., None], deep[None, None] * .8, A)
        A = A * (1 + .22 * pile[..., None])
        # worn through at the near edge: pile rubbed down to warp
        worn = smooth(.55, 1.5, fbm(H, W, 16, s.seed + 83)) * smooth(60, 10, dz)
        A = mix(A, np.array([.45, .38, .30]), worn * .55)
        s.A = np.where(m[..., None], A, s.A)
        s.K = np.where(m, 1 - .10 * smooth(.3, 1.4, pile), s.K)
        s.R = np.where(m, 3 + .9 * pile, s.R)
        # the shadow the rug's thickness throws, and its fringe at the near edge
        outer = (d <= 0) & (d > -5) & (s.yy >= fy)
        s.K *= 1 - .55 * outer
        fr = (Z > z1) & (Z < z1 + 34) & (np.abs(X - cxw) < half) & (s.yy >= fy)
        th = np.abs(((X / 7.0) % 1) - .5) * 2
        A2 = np.array([.76, .68, .52])[None, None] * (.55 + .6 * th[..., None]) * (1 - .4 * ((Z - z1) / 34)[..., None])
        keep = fr & (th > .32 + .25 * noise(H, W, 2, s.seed + 85))
        s.A = np.where(keep[..., None], A2, s.A)
        s.K = np.where(keep, 1.0, s.K)
        s.R = np.where(keep, 2.0, s.R)

    # ── lights ────────────────────────────────────────────────────────────────
    def normals(s, k=.55):
        R = ndi.gaussian_filter(s.R, .6)
        gy, gx = np.gradient(R)
        s.nx, s.ny = -gx * k, -gy * k
        n = np.sqrt(s.nx ** 2 + s.ny ** 2 + 1)
        s.nx, s.ny, s.nz = s.nx / n, s.ny / n, 1 / n
        s.brush = 1 + .13 * fbm(s.H, s.W, 26, s.seed + 90) + .05 * aniso(s.H, s.W, 2, 22, s.seed + 91)
        s.floorm = None

    def lamp(s, x, y, z, col, power, radius, mask=None):
        dx, dy = x - s.xx, y - s.yy
        d2 = dx * dx + dy * dy + z * z
        d = np.sqrt(d2)
        ndl = np.clip((dx * s.nx + dy * s.ny + z * s.nz) / d, 0, 1)
        fall = 1 / (1 + (d / radius) ** 2) ** 1.25
        # the falloff laid in brushed tones, not an airbrush
        a = ndl * fall * s.brush * power
        if mask is not None:
            a = a * mask
        s.L += a[..., None] * col
        # the shine on a turned edge facing the flame
        hv = np.clip(ndl, 0, 1) ** 16 * fall * power * .35
        if mask is not None:
            hv = hv * mask
        s.L += hv[..., None] * col

    def ambient(s, col, a):
        s.L += np.array(col)[None, None] * a

    def darken(s, x, y, rx, ry, a, soft=.7):
        d = np.sqrt(((s.xx - x) / rx) ** 2 + ((s.yy - y) / ry) ** 2)
        s.L *= (1 - a * smooth(1, soft * .0 + .15, d))[..., None]

    def finish(s, name, quality=86):
        H, W = s.H, s.W
        # ink where the relief turns hard, on the side away from the eye
        lap = ndi.gaussian_laplace(s.R, 1.0)
        s.K *= 1 - .35 * smooth(.35, 1.4, lap)
        L = s.L
        # the shadow side of the palette goes plum, never grey
        lum = L.mean(-1, keepdims=True)
        tint = np.array([1.04, .90, 1.16])[None, None]
        L = mix(L * tint, L, smooth(.05, .5, lum[..., 0]))
        C = s.A * L * s.K[..., None] + s.add
        # the painted hand: filmic shoulder, then clumped strokes, then tooth
        C = 1 - np.exp(-C * 1.35)
        C = ndi.median_filter(C, size=(3, 3, 1))
        C = C * (1 + .032 * aniso(H, W, .8, 5, s.seed + 95))[..., None]
        C = C * (1 + .026 * aniso(H, W, 5, .8, s.seed + 96))[..., None]
        white = np.random.default_rng(s.seed + 97).normal(0, 1, (H, W))
        C = C + (.011 + .045 * np.sqrt(np.clip(C.mean(-1), 0, 1)))[..., None] * white[..., None] * .55
        im = Image.fromarray((np.clip(C, 0, 1) * 255 + .5).astype(np.uint8))
        path = OUT / f'{name}.webp'
        im.save(path, quality=quality, method=6)
        print(name, im.size, path.stat().st_size)
        return C


# ── moonlight: a real casement falling across the room ───────────────────────
def casement(s, cx, top, w, h, floor_y, lean, wains_y0, wains_y1, seed):
    """Painted light from one lancet. `lean` is +1 toward screen right. Returns nothing; adds to s."""
    H, W = s.H, s.W
    x, y = s.xx, s.yy
    y0 = top + h * .5
    # the shaft in the air: bands parted by the mullion and leads, leaning in,
    # widening a little, broken along its length by brushed noise
    t = (y - y0)
    wid = w * .5 * (1 + np.clip(t, 0, None) / (H * 1.3))
    cxt = cx + lean * t * .52
    wob = 5 * noise(H, W, 26, seed)
    u = (x - cxt + wob) / wid          # -1..1 across the shaft
    edge = smooth(1.06, .86, np.abs(u))
    bars = 1 - .9 * smooth(.10, .05, np.abs(u))
    streak = 1 + .36 * aniso(H, W, 50, 3, seed + 1) + .2 * aniso(H, W, 120, 9, seed + 2)
    # streak along the lean, not along the screen's vertical
    sh = np.round(lean * (y - y0) * .52).astype(int)
    xi = np.mod((x - sh).astype(int), W)
    yi = y.astype(int)
    streak = streak[yi, xi]
    fall = smooth(0, 60, t) * (1 - .55 * smooth(0, floor_y - y0, t))
    air = np.clip(edge * bars * streak * fall, 0, 2) * .082
    s.add += air[..., None] * MOON * (y < floor_y + 6)[..., None]

    # the same light landing: on the wainscot's panels...
    ws = (y >= wains_y0) & (y <= wains_y1)
    u2 = (x - (cxt)) / wid
    v2 = (y - wains_y0) / (wains_y1 - wains_y0)
    b = smooth(1.03, .92, np.abs(u2 + .05 * noise(H, W, 8, seed + 3)))
    b *= 1 - .92 * smooth(.11, .07, np.abs(u2))
    b *= 1 - .9 * smooth(.07, .04, np.abs(((v2 * 2.0 + .5) % 1) - .5))
    land = np.clip(b, 0, 1) * ws
    # ...and on the floor, the casement thrown long toward the room, arch last
    fy = floor_y
    yy = (y - fy)
    fx0 = cx + lean * (fy - y0) * .52
    span = H - fy
    near = yy / span
    # cast: width grows as it comes toward us; it leans further in
    fcx = fx0 + lean * near * span * 1.15
    fw = w * .62 * (1 + near * 1.05)
    uf = (x - fcx) / fw
    arch_top = .02 + .24 * np.abs(uf) ** 2.2
    inside = smooth(1.02, .9, np.abs(uf + .04 * noise(H, W, 7, seed + 4)))
    inside *= smooth(arch_top, arch_top + .03, near) * smooth(1.0, .86, near)
    cross = 1 - .92 * smooth(.09, .05, np.abs(uf))
    cross *= 1 - .9 * smooth(.055, .03, np.abs(((near * 3.0 + .5) % 1) - .5))
    fl = np.clip(inside * cross, 0, 1) * (y >= fy)
    mask = np.clip(land * .66 + fl, 0, 1) * (1 + .12 * noise(H, W, 5, seed + 5))
    s.lamp(float(cx), float(top), 240.0, MOON, 0.0, 400.0)  # keep brush seeded
    dx, dy = lean * 40.0, -90.0
    ndl = np.clip((dx * s.nx + dy * s.ny + 90 * s.nz) / np.sqrt(dx * dx + dy * dy + 90 * 90), 0, 1)
    s.L += (mask * ndl * 2.25 * s.brush)[..., None] * MOON
    # dust, hanging in the shaft
    r = np.random.default_rng(seed + 6)
    dust = np.zeros((H, W))
    for _ in range(int(h * .55)):
        ty = r.uniform(30, floor_y - y0)
        px = cx + lean * ty * .52 + r.uniform(-1, 1) * w * .5 * (1 + ty / (H * 1.3))
        py = y0 + ty
        ix, iy = int(px), int(py)
        if 1 <= ix < W - 1 and 1 <= iy < H - 1:
            dust[iy, ix] += r.uniform(.2, 1)
            if r.random() < .25:
                dust[iy, ix + 1] += r.uniform(.1, .5)
    dust = dust + ndi.gaussian_filter(dust, 1.2) * 2.2
    s.add += (np.clip(dust, 0, 1) * .22)[..., None] * (MOON * .7 + .3)


def event_room(W, H, g, name, seed):
    s = Room(W, H, seed)
    s.wall(int(H * .083), g['rail'])
    s.wainscot(g['rail'], g['floor'], g['panel'])
    s.flags(g['floor'], g['depth'], W / 2, g['cell'])
    s.normals()
    s.ambient((.52, .42, .70), .30)
    # the corner candles
    for sx in (g['corner_x'], W - g['corner_x']):
        s.lamp(sx, g['corner_y'], 90, CANDLE, 1.05, W * .15)
    # the sconces: low on the wall, pushing light up the paper and across the panels
    for sx in (g['sconce_x'], W - g['sconce_x']):
        s.lamp(sx, g['sconce_y'], 62, CANDLE, 1.8, W * .115)
    # the floor candles: they rake the skirting and the stones
    for sx in (g['candle_x'], W - g['candle_x']):
        s.lamp(sx, g['candle_y'], 44, CANDLE, 1.5, W * .082)
    # the reading desk's lamp, spilling out past the page on both sides and down the foot
    s.lamp(W / 2, g['page_y'], 150, EMBER, 1.3, W * .22)
    # moonlight, lancet by lancet
    for lean, cx in ((1, g['win_cx']), (-1, W - g['win_cx'])):
        casement(s, cx, g['win_top'], g['win_w'], g['win_h'], g['floor'], lean,
                 g['rail'], g['floor'], seed + (10 if lean > 0 else 30))
    # whatever stands on the flags throws a shadow away from the flame beside it
    for x, y, rx, ry in g['shadows']:
        s.darken(x, y, rx, ry, .82)
        s.darken(W - x, y, rx, ry, .82) if rx < W * .03 else None
    # the paper behind the room's name stays quiet enough to read on
    s.darken(W / 2, g['name_y'], W * .36, H * .055, .62)
    # the foot of the desk stands in its own pooled shadow
    s.darken(W / 2, g['foot_y'], W * .15, H * .05, .6)
    # the walls close in at the very edge, but the paper never goes to void
    d = np.sqrt(((s.xx - W / 2) / (W * .62)) ** 2 + ((s.yy - H * .5) / (H * .72)) ** 2)
    s.L *= (1 - .42 * smooth(.72, 1.15, d))[..., None]
    s.finish(name)


def rest_room(W, H, g, name, seed):
    s = Room(W, H, seed)
    s.wall(int(H * .083), g['rail'])
    s.wainscot(g['rail'], g['floor'], g['panel'])
    s.boards(g['floor'], g['depth'], g['vx'], g['plank'])
    s.rug(g['rug_x'], g['rug_half'], g['rug_z0'], g['rug_z1'])
    s.normals()
    s.ambient((.50, .40, .68), .30)
    for sx in (g['corner_x'], W - g['corner_x']):
        s.lamp(sx, g['corner_y'], 90, CANDLE, 1.05, W * .15)
    # the fort's lantern glows out past its frame
    s.lamp(g['fort_x'], g['fort_y'], 190, EMBER, 1.25, W * .2)
    # the two candles on the console, low and close, pool on the rug
    for sx in g['ledge_x']:
        s.lamp(sx, g['ledge_y'], 60, CANDLE, 1.25, W * .085)
        s.lamp(sx, g['ledge_y'] + (H - g['ledge_y']) * .62, 58, CANDLE, 1.9, W * .085)
    # a warm pool at the foot of the choices, then the long fall to the moon
    s.lamp(W * .63, H * .93, 90, EMBER, .75, W * .10)
    s.lamp(W * 1.0, H * .25, 260, MOON, .5, W * .28)
    s.darken(W / 2, g['name_y'], W * .34, H * .05, .62)
    # moon on the boards beside the way out
    X, Z, sc = s.floor_uv(g['floor'], g['depth'], g['vx'])
    u = (s.xx - g['moon_x'] - (s.yy - g['floor']) * -.7) / (W * .055)
    v = (s.yy - g['floor'] - 8) / (H - g['floor'] - 12)
    pane = smooth(1.02, .92, np.abs(u)) * smooth(0, .05, v) * smooth(1, .9, v) * (s.yy >= g['floor'])
    pane = pane * (1 - .9 * smooth(.07, .03, np.abs(u))) * (1 - .85 * smooth(.05, .02, np.abs(((v * 2) % 1) - .5)))
    s.L += (pane * 1.1 * s.brush * np.clip(s.nz, 0, 1))[..., None] * MOON
    # console's shadow on the rug and the wall behind it, thrown away from both flames
    s.darken(g['fort_x'], g['floor'] + (H - g['floor']) * .20, W * .13, (H - g['floor']) * .26, .72)
    d = np.sqrt(((s.xx - W / 2) / (W * .62)) ** 2 + ((s.yy - H * .5) / (H * .72)) ** 2)
    s.L *= (1 - .42 * smooth(.72, 1.15, d))[..., None]
    s.finish(name)


def console(name, W=1100, H=280, seed=5710):
    """The low walnut console the fort's frame stands on: apron, turned legs, bun feet. Alpha."""
    s = Room(W, H, seed)
    A, G = s.wood(False, seed, (.30, .185, .12))
    Av, Gv = s.wood(True, seed + 5, (.28, .17, .11))
    alpha = np.zeros((H, W))
    R = np.zeros((H, W))
    # apron with a scalloped lower edge and a shell at its middle
    ax = (s.xx - W / 2) / (W / 2)
    edge = 74 + 16 * np.cos(ax * 9 * np.pi) * smooth(1.0, .75, np.abs(ax)) + 30 * smooth(.22, .0, np.abs(ax)) - 20 * smooth(.8, 1, np.abs(ax))
    apron = (s.yy < edge) & (np.abs(ax) < .955)
    alpha[apron] = 1
    d = edge - s.yy
    R = np.where(apron, 8 * smooth(0, 7, d) + 3 * np.sin(np.clip(s.yy / 30, 0, 1) * np.pi) + G * .8, R)
    s.A = np.where(apron[..., None], A, s.A)
    # the shell, carved
    th = np.arctan2(s.yy - 18, s.xx - W / 2); rad = np.hypot(s.xx - W / 2, s.yy - 18)
    shell = (rad < 76) & (s.yy > 18)
    R = np.where(shell, R + 4.5 * np.abs(np.sin(th * 9)) * smooth(76, 66, rad), R)
    # one worn gilt line along the apron
    g = (np.abs(d - 11) < 1.6) & apron
    wear = fbm(H, W, 9, seed + 7)
    s.A = np.where((g & (wear > -.9))[..., None], np.array([.70, .50, .26])[None, None], s.A)
    # the legs: a lathe profile
    def prof(t):
        pts = [(0, 40), (.1, 40), (.13, 26), (.2, 22), (.26, 34), (.36, 40), (.46, 28), (.54, 18), (.72, 15), (.82, 19), (.87, 30), (.93, 34), (1, 24)]
        ts, rs = zip(*pts)
        return np.interp(t, ts, rs)
    for cx in (W * .085, W * .915):
        y0, y1 = 40, H - 4
        t = (s.yy - y0) / (y1 - y0)
        rr = prof(np.clip(t, 0, 1))
        u = (s.xx - cx) / rr
        leg = (np.abs(u) < 1) & (t >= 0) & (t <= 1)
        alpha[leg] = 1
        R = np.where(leg, np.sqrt(np.clip(1 - u * u, 0, 1)) * rr * .9, R)
        s.A = np.where(leg[..., None], Av, s.A)
        band = leg & ((np.abs(t - .13) < .012) | (np.abs(t - .87) < .012))
        s.A = np.where(band[..., None], np.array([.7, .5, .26])[None, None], s.A)
    s.R = R
    s.normals(.8)
    s.ambient((.55, .44, .62), .32)
    s.lamp(W * .03, -10, 120, CANDLE, 1.9, W * .22)
    s.lamp(W * .97, -10, 120, CANDLE, 1.9, W * .22)
    s.lamp(W * .5, 120, 220, EMBER, .55, W * .3)
    C = s.A * s.L * s.K[..., None]
    lap = ndi.gaussian_laplace(R, 1.0)
    C *= (1 - .4 * smooth(.3, 1.2, lap))[..., None]
    C = 1 - np.exp(-C * 1.35)
    C = ndi.median_filter(C, size=(3, 3, 1))
    a = ndi.gaussian_filter(alpha, .8)
    rgba = np.dstack([np.clip(C, 0, 1), a])
    im = Image.fromarray((rgba * 255 + .5).astype(np.uint8), 'RGBA')
    path = OUT / f'{name}.webp'
    im.save(path, quality=88, method=6)
    print(name, im.size, path.stat().st_size)


