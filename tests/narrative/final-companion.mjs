// Real reward -> Run.end -> installed story listener -> pending ending route.
// Uses the storage module's built-in memory backend, not a browser campaign.
import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,n){
  if(s==='three')return {url:new URL('../../game/vendor/three.module.js',import.meta.url).href,shortCircuit:true};
  return n(s,c);
}});
const {Run}=await import('../../game/src/state/run.js');
const {Save}=await import('../../game/src/core/save.js');
const {COMPANIONS,NodeType}=await import('../../game/src/data/schema.js');
const N=await import('../../game/src/state/narrative.js');
const {installStory}=await import('../../game/src/ui/story.js');
const ctx={scenes:{register(){}}};installStory(ctx);
Save.reset();
Save.data.companionsRescued=COMPANIONS.filter(c=>c.slug!=='wisp').map(c=>c.slug);
const r=new Run({seed:322,kid:'samir'});r.region='heart';r.regionIndex=r.wings-1;r._buildMap();
ctx.run=r;const boss=r.map.nodes.find(n=>n.type===NodeType.BOSS);r.currentNodeId=boss.id;
r._prepareReward(boss,NodeType.BOSS,{navigate:false});
r.claimReward();await Save.flush();
assert.equal(r.result,'victory');assert.deepEqual(r.companionsFreed,['wisp']);
assert.deepEqual(Save.data.narrative.pendingEnding.companions,['wisp']);
assert.equal(Save.hasRun(),false,'finished run no longer supplies a saved roster');
let route=N.narrativeRoute(ctx,'gameover',{});
assert.equal(route.units[0].id,'COMP-wisp-0');assert.equal(route.units[0].title,'Wisp');
assert.equal(route.units.at(-1).runDone,'ending');
Save.load();route=N.narrativeRoute({run:null},'title',{});
assert.equal(route.units[0].id,'COMP-wisp-0','serialized pending roster recovers without active Run');
Save.blocked={reason:'fixture'};
assert.equal(await N.commitStory(s=>{s.seen['COMP-wisp-0']=true;}),false);
assert.equal(N.narrativeRoute({run:null},'title',{}).units[0].id,'COMP-wisp-0','failed acknowledgement leaves introduction pending');
Save.blocked=null;
assert.equal(await N.commitStory(s=>{s.seen['COMP-wisp-0']=true;}),true);
Save.load();assert.equal(N.narrativeRoute({run:null},'title',{}).units.some(u=>u.id==='COMP-wisp-0'),false,'acknowledged introduction does not replay');
delete Save.data.narrative.seen['COMP-wisp-0'];
delete Save.data.narrative.pendingEnding.companions;
r.companionsFreed.push('wisp');
assert.equal(N.narrativeRoute(ctx,'gameover',{}).units.filter(u=>u.id==='COMP-wisp-0').length,1,'legacy record uses matching live run once');
assert.equal(N.narrativeRoute({run:null},'title',{}).units.some(u=>u.id==='COMP-wisp-0'),false,'legacy record invents no recovered roster');
Save.data.narrative.pendingEnding.companions=[];
assert.equal(N.narrativeRoute(ctx,'gameover',{}).units.some(u=>u.id==='COMP-wisp-0'),false,'explicit empty roster wins over live run');
Save.data.narrative.pendingEnding.companions=['wisp'];r.session={remote:true};
assert.equal(N.narrativeRoute(ctx,'gameover',{}).units[0].id,'COMP-wisp-0','post-run network finale includes introduction');
Save.data.narrative.pendingEnding=null;r.storyMemory=true;
route=N.narrativeRoute(ctx,'gameover',{});
assert.equal(route.units[0].id,'COMP-wisp-0');
assert.equal(route.units.filter(u=>u.id==='COMP-wisp-0').length,1);
assert.equal(route.units[1].id,'END-MEMORY');
await Save.flush();
console.log('PASS: real final reward introduces Wisp before ending; saved roster survives loss of Run; failed acknowledgement retries; committed intro is idempotent; legacy fallback, explicit empty, remote finale and memory route remain safe.');
